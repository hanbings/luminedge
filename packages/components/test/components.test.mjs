import assert from 'node:assert/strict';
import test from 'node:test';
import { createCalendar, createMenu, createPagination, createTabs, createTooltip, showToast } from '@luminedge/ui';
import { addCalendarDays, addCalendarMonths, formatCalendarDate, parseCalendarDate } from '../dist/calendar-date.js';
import { FakeDocument, element, fire } from './fixtures/dom.mjs';

test('calendar date arithmetic handles leap years, short months and supported years', () => {
  assert.equal(parseCalendarDate('2023-02-29'), null);
  assert.equal(parseCalendarDate('2024-13-01'), null);
  assert.equal(parseCalendarDate('0000-01-01'), null);
  assert.equal(formatCalendarDate(parseCalendarDate('0001-01-01')), '0001-01-01');
  assert.equal(formatCalendarDate(addCalendarMonths(parseCalendarDate('2024-01-31'), 1)), '2024-02-29');
  assert.equal(formatCalendarDate(addCalendarMonths(parseCalendarDate('2023-03-31'), -1)), '2023-02-28');
  assert.equal(formatCalendarDate(addCalendarDays(parseCalendarDate('2024-02-28'), 1)), '2024-02-29');
  assert.equal(addCalendarDays(parseCalendarDate('9999-12-31'), 1), null);
});

test('tabs select panels, skip disabled tabs and remove listeners', () => {
  const doc = new FakeDocument();
  const root = element(doc, 'div');
  const list = element(doc, 'div', { role: 'tablist' });
  const tabs = ['one', 'two', 'three'].map((name) => element(doc, 'a', { id: `tab-${name}`, role: 'tab', 'aria-controls': `panel-${name}`, 'aria-selected': String(name === 'one') }));
  tabs[1].setAttribute('aria-disabled', 'true');
  const panels = ['one', 'two', 'three'].map((name) => element(doc, 'div', { id: `panel-${name}`, role: 'tabpanel' }));
  list.append(...tabs);
  root.append(list, ...panels);
  doc.body.append(root);
  const events = [];
  root.addEventListener('le:tabchange', (event) => events.push(event.detail.id));
  const controller = createTabs(root);
  assert.equal(panels[0].hidden, false);
  assert.equal(panels[1].hidden, true);
  fire(tabs[0], 'keydown', { key: 'ArrowRight' });
  assert.equal(doc.activeElement, tabs[2]);
  assert.equal(tabs[2].getAttribute('aria-selected'), 'true');
  assert.equal(panels[2].hidden, false);
  assert.equal(controller.select('tab-two'), false);
  fire(tabs[2], 'keydown', { key: 'ArrowRight' });
  assert.equal(doc.activeElement, tabs[0]);
  assert.deepEqual(events, ['tab-three', 'tab-one']);
  tabs[0].setAttribute('aria-disabled', 'true');
  tabs[2].setAttribute('aria-disabled', 'true');
  fire(tabs[0], 'keydown', { key: 'ArrowRight' });
  assert.deepEqual(events, ['tab-three', 'tab-one']);
  tabs[0].removeAttribute('aria-disabled');
  tabs[2].removeAttribute('aria-disabled');
  controller.destroy();
  fire(tabs[2], 'click');
  assert.equal(tabs[0].getAttribute('aria-selected'), 'true');
  assert.deepEqual(events, ['tab-three', 'tab-one']);
});

test('pagination reports page changes and respects first and last pages', () => {
  const doc = new FakeDocument();
  const root = element(doc, 'nav');
  const buttons = ['previous', '1', '2', '3', 'next'].map((value) => element(doc, 'button', { 'data-le-page': value }));
  buttons[1].setAttribute('aria-current', 'page');
  root.append(...buttons);
  doc.body.append(root);
  const pages = [];
  root.addEventListener('le:pagechange', (event) => pages.push(event.detail.page));
  const controller = createPagination(root);
  assert.equal(buttons[0].disabled, true);
  fire(buttons[4], 'click');
  assert.equal(controller.getPage(), 2);
  assert.equal(buttons[2].getAttribute('aria-current'), 'page');
  assert.equal(controller.setPage(3), true);
  assert.equal(buttons[4].disabled, true);
  assert.equal(controller.setPage(4), false);
  assert.deepEqual(pages, [2, 3]);
  controller.destroy();
  fire(buttons[0], 'click');
  assert.equal(controller.getPage(), 3);
});

test('calendar navigation, selection and limits work together', () => {
  const doc = new FakeDocument();
  const root = element(doc, 'div');
  const header = element(doc, 'div');
  const previous = element(doc, 'button', { 'data-calendar-previous': '' });
  const label = element(doc, 'span', { 'data-calendar-label': '' });
  const next = element(doc, 'button', { 'data-calendar-next': '' });
  const table = element(doc, 'table', { 'data-calendar-grid': '' });
  const weekdays = element(doc, 'tr', { 'data-calendar-weekdays': '' });
  const body = element(doc, 'tbody', { 'data-calendar-body': '' });
  header.append(previous, label, next);
  table.append(weekdays, body);
  root.append(header, table);
  doc.body.append(root);
  const values = [];
  root.addEventListener('le:datechange', (event) => values.push(event.detail.value));
  const calendar = createCalendar(root, { value: '2024-01-31', min: '2024-01-01', max: '2024-03-15', locale: 'en-US' });
  assert.equal(previous.disabled, true);
  assert.equal(weekdays.children.length, 7);
  const january31 = root.querySelector('button[data-calendar-date="2024-01-31"]');
  assert.equal(january31.getAttribute('aria-pressed'), 'true');
  fire(january31, 'keydown', { key: 'PageDown', shiftKey: false });
  const february29 = root.querySelector('button[data-calendar-date="2024-02-29"]');
  assert.equal(doc.activeElement, february29);
  assert.equal(calendar.getDate(), '2024-01-31');
  fire(february29, 'click');
  assert.equal(calendar.getDate(), '2024-02-29');
  assert.equal(calendar.setDate('2024-03-16'), false);
  assert.equal(calendar.setDate('2024-02-30'), false);
  assert.equal(calendar.setDate('2024-03-15'), true);
  assert.equal(next.disabled, true);
  assert.equal(calendar.setDate(null), true);
  assert.equal(calendar.getDate(), null);
  assert.deepEqual(values, ['2024-02-29', '2024-03-15', null]);
  calendar.destroy();
  const monthBefore = label.textContent;
  fire(previous, 'click');
  assert.equal(label.textContent, monthBefore);
  assert.equal(calendar.getDate(), null);
});

test('menu closes after selection, Escape or an outside click', () => {
  const doc = new FakeDocument();
  const root = element(doc, 'details');
  const summary = element(doc, 'summary');
  const item = element(doc, 'button', { 'data-le-menu-close': '' });
  const outside = element(doc, 'button');
  root.append(summary, item);
  doc.body.append(root, outside);
  const menu = createMenu(root);
  menu.open();
  fire(item, 'click');
  assert.equal(root.open, false);
  assert.equal(doc.activeElement, summary);
  menu.open();
  fire(root, 'keydown', { key: 'Escape' });
  assert.equal(root.open, false);
  menu.open();
  outside.focus();
  fire(outside, 'pointerdown');
  assert.equal(root.open, false);
  assert.equal(doc.activeElement, outside);
  menu.destroy();
});

test('tooltip responds to hover, focus, touch and Escape, and restores attributes', () => {
  const doc = new FakeDocument();
  const host = element(doc, 'span');
  const trigger = element(doc, 'button', { 'aria-describedby': 'existing' });
  const tooltip = element(doc, 'span', { id: 'tip' });
  const outside = element(doc, 'button');
  host.append(trigger, tooltip);
  doc.body.append(host, outside);
  const controller = createTooltip(trigger, tooltip);
  assert.equal(tooltip.hidden, true);
  assert.equal(trigger.getAttribute('aria-describedby'), 'existing tip');
  fire(host, 'mouseenter');
  assert.equal(tooltip.hidden, false);
  fire(doc, 'keydown', { key: 'Escape' });
  assert.equal(tooltip.hidden, true);
  fire(host, 'mouseleave');
  fire(host, 'focusin');
  assert.equal(tooltip.hidden, false);
  fire(host, 'focusout', { relatedTarget: outside });
  assert.equal(tooltip.hidden, true);
  fire(trigger, 'pointerdown', { pointerType: 'touch' });
  assert.equal(tooltip.hidden, false);
  fire(outside, 'pointerdown', { pointerType: 'touch' });
  assert.equal(tooltip.hidden, true);
  controller.destroy();
  assert.equal(trigger.getAttribute('aria-describedby'), 'existing');
  assert.equal(tooltip.getAttribute('role'), null);
});

test('toast treats messages as text, restores focus and pauses timed dismissal', async () => {
  const doc = new FakeDocument();
  const trigger = element(doc, 'button');
  const region = element(doc, 'div');
  doc.body.append(trigger, region);
  trigger.focus();
  assert.throws(() => showToast(region, { message: 'bad duration', duration: -1 }));
  const controller = showToast(region, { message: '<b>safe text</b>', variant: 'success' });
  const toast = region.children[0];
  assert.equal(toast.children[0].textContent, '<b>safe text</b>');
  assert.equal(toast.children.length, 2);
  toast.children[1].focus();
  fire(toast.children[1], 'click');
  assert.equal(region.children.length, 0);
  assert.equal(doc.activeElement, trigger);
  controller.dismiss();

  showToast(region, { message: 'timed', duration: 20 });
  const timed = region.children[0];
  fire(timed, 'mouseenter');
  await new Promise((resolve) => setTimeout(resolve, 45));
  assert.equal(region.children.length, 1);
  fire(timed, 'mouseleave');
  await new Promise((resolve) => setTimeout(resolve, 45));
  assert.equal(region.children.length, 0);
});
